@asynccontextmanager
async def lifespan(app: FastAPI):
    """Application startup and shutdown."""
    print("  Support Agent API starting up...")
    yield
    print("  Support Agent API shutting down...")


app = FastAPI(
    title="AI Support Agent API",
    description="Customer support ticket processing with AI agents",
    version="1.0.0",
    lifespan=lifespan,
)

# CORS for web frontends
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],  # Restrict in production
    allow_methods=["*"],
    allow_headers=["*"],
)


