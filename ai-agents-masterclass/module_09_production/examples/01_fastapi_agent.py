# ──────────────────────────────────────────────────────────────
# Pydantic Models (Request/Response Schemas)
# ──────────────────────────────────────────────────────────────

class TicketRequest(BaseModel):
    """Incoming support ticket from the API."""
    subject: str = Field(..., min_length=5, max_length=200, description="Ticket subject")
    body: str = Field(..., min_length=10, max_length=10000, description="Ticket description")
    customer_email: str = Field(..., description="Customer's email address")
    priority: Optional[str] = Field(None, description="Optional priority hint: low/medium/high")

    @field_validator("priority")
    @classmethod
    def validate_priority(cls, v):
        if v is not None and v not in ("low", "medium", "high"):
            raise ValueError("priority must be 'low', 'medium', or 'high'")
        return v

    @field_validator("customer_email")
    @classmethod
    def validate_email(cls, v):
        if "@" not in v or "." not in v.split("@")[-1]:
            raise ValueError("Invalid email address format")
        return v.lower()

    model_config = {
        "json_schema_extra": {
            "example": {
                "subject": "Can't log in to my account",
                "body": "I forgot my password and the reset email isn't arriving.",
                "customer_email": "alice@example.com",
                "priority": "high",
            }
        }
    }


class TicketResponse(BaseModel):
    """Response after submitting a ticket."""
    ticket_id: str
    status: str
    message: str
    created_at: str


class TicketDetail(BaseModel):
    """Full ticket details including agent response."""
    ticket_id: str
    subject: str
    customer_email: str
    status: str
    category: Optional[str]
    priority: str
    agent_response: Optional[str]
    should_escalate: bool
    confidence: float
    processing_time_ms: Optional[int]
    created_at: str
    updated_at: str


class HealthResponse(BaseModel):
    """Health check response."""
    status: str
    version: str
    uptime_seconds: float
    checks: dict[str, str]


class MetricsResponse(BaseModel):
    """Performance metrics."""
    total_tickets: int
    processed_tickets: int
    pending_tickets: int
    avg_processing_time_ms: float
    escalation_rate: float


