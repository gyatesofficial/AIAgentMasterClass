ticket_store: dict[str, dict] = {}
metrics_store = {
    "total": 0,
    "processed": 0,
    "total_processing_ms": 0,
    "escalations": 0,
}
app_start_time = time.time()


# ──────────────────────────────────────────────────────────────
# Agent Logic (simplified for demo)
# ──────────────────────────────────────────────────────────────

def process_ticket_sync(ticket_id: str, subject: str, body: str, email: str) -> dict:
    """
    Process a support ticket using the AI agent.

    In production, this would call the full agent pipeline.
    Here we demonstrate the structure with mock logic.
    """
    start = time.time()

    # Triage
    text = f"{subject} {body}".lower()
    if any(w in text for w in ["charge", "billing", "invoice", "refund"]):
        category = "billing"
        should_escalate = True
    elif any(w in text for w in ["error", "bug", "crash"]):
        category = "technical"
        should_escalate = True
    elif any(w in text for w in ["password", "login", "access"]):
        category = "account_access"
        should_escalate = False
    else:
        category = "general"
        should_escalate = False

    # Extract name from email
    username = email.split("@")[0]
    name = username.replace(".", " ").replace("_", " ").title()

    # Generate response
    if category == "account_access":
        response = (
            f"Hi {name},\n\n"
            f"For account access issues, please try:\n"
            f"1. Visit the login page and click 'Forgot Password'\n"
            f"2. Enter your email address\n"
            f"3. Check your inbox for a reset link (valid 24 hours)\n\n"
            f"If the issue persists, please reply to this ticket."
        )
        confidence = 0.88
    elif category == "billing":
        response = (
            f"Hi {name},\n\n"
            f"Our billing team will review your account and respond within 1 business day. "
            f"For urgent billing issues, please email billing@example.com."
        )
        confidence = 0.82
    else:
        response = (
            f"Hi {name},\n\n"
            f"Thank you for contacting us. Our team will investigate and respond within 24 hours."
        )
        confidence = 0.70

    processing_time = int((time.time() - start) * 1000)

    return {
        "category": category,
        "should_escalate": should_escalate,
        "agent_response": response,
        "confidence": confidence,
        "processing_time_ms": processing_time,
    }


# ──────────────────────────────────────────────────────────────
# Background Task
# ──────────────────────────────────────────────────────────────

async def process_ticket_background(ticket_id: str):
    """
    Process a ticket asynchronously.

    FastAPI background tasks run after the response is sent to the client,
    so the client gets an immediate acknowledgment while processing happens.
    """
    ticket = ticket_store.get(ticket_id)
    if not ticket:
        return

    try:
        result = process_ticket_sync(
            ticket_id,
            ticket["subject"],
            ticket["body"],
            ticket["customer_email"],
        )

        ticket.update({
            "status": "resolved" if not result["should_escalate"] else "escalated",
            "category": result["category"],
            "agent_response": result["agent_response"],
            "should_escalate": result["should_escalate"],
            "confidence": result["confidence"],
            "processing_time_ms": result["processing_time_ms"],
            "updated_at": datetime.now(timezone.utc).isoformat(),
        })

        # Update metrics
        metrics_store["processed"] += 1
        metrics_store["total_processing_ms"] += result["processing_time_ms"]
        if result["should_escalate"]:
            metrics_store["escalations"] += 1

    except Exception as e:
        ticket.update({
            "status": "error",
            "error_message": str(e),
            "updated_at": datetime.now(timezone.utc).isoformat(),
        })


