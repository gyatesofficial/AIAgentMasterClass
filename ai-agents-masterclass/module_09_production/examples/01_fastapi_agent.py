@app.post("/tickets", response_model=TicketResponse, status_code=202)
async def submit_ticket(
    request: TicketRequest,
    background_tasks: BackgroundTasks,
    x_correlation_id: Optional[str] = Header(None),
):
    """
    Submit a support ticket for AI processing.

    Returns immediately with a ticket ID. Processing happens in background.
    Poll GET /tickets/{id} for the result.

    HTTP 202 Accepted means: "we received it, processing in progress."
    """
    ticket_id = f"TKT-{str(uuid.uuid4())[:8].upper()}"
    now = datetime.now(timezone.utc).isoformat()

    # Store ticket with initial status
    ticket_store[ticket_id] = {
        "ticket_id": ticket_id,
        "subject": request.subject,
        "body": request.body,
        "customer_email": request.customer_email,
        "priority": request.priority or "medium",
        "status": "processing",
        "category": None,
        "agent_response": None,
        "should_escalate": False,
        "confidence": 0.0,
        "processing_time_ms": None,
        "created_at": now,
        "updated_at": now,
        "correlation_id": x_correlation_id,
    }

    metrics_store["total"] += 1

    # Queue background processing
    background_tasks.add_task(process_ticket_background, ticket_id)

    return TicketResponse(
        ticket_id=ticket_id,
        status="processing",
        message="Ticket received. Processing in background.",
        created_at=now,
    )


@app.get("/tickets/{ticket_id}", response_model=TicketDetail)
async def get_ticket(ticket_id: str):
    """
    Retrieve a ticket by ID.

    Returns the current status and agent response if processing is complete.
    """
    ticket = ticket_store.get(ticket_id)
    if not ticket:
        raise HTTPException(
            status_code=404,
            detail=f"Ticket {ticket_id} not found",
        )

    return TicketDetail(
        ticket_id=ticket["ticket_id"],
        subject=ticket["subject"],
        customer_email=ticket["customer_email"],
        status=ticket["status"],
        category=ticket.get("category"),
        priority=ticket["priority"],
        agent_response=ticket.get("agent_response"),
        should_escalate=ticket.get("should_escalate", False),
        confidence=ticket.get("confidence", 0.0),
        processing_time_ms=ticket.get("processing_time_ms"),
        created_at=ticket["created_at"],
        updated_at=ticket["updated_at"],
    )


@app.get("/tickets", response_model=list[TicketDetail])
async def list_tickets(
    status: Optional[str] = None,
    limit: int = 20,
):
    """
    List tickets with optional status filter.
    """
    tickets = list(ticket_store.values())

    if status:
        tickets = [t for t in tickets if t.get("status") == status]

    tickets.sort(key=lambda t: t["created_at"], reverse=True)
    tickets = tickets[:limit]

    return [
        TicketDetail(
            ticket_id=t["ticket_id"],
            subject=t["subject"],
            customer_email=t["customer_email"],
            status=t["status"],
            category=t.get("category"),
            priority=t["priority"],
            agent_response=t.get("agent_response"),
            should_escalate=t.get("should_escalate", False),
            confidence=t.get("confidence", 0.0),
            processing_time_ms=t.get("processing_time_ms"),
            created_at=t["created_at"],
            updated_at=t["updated_at"],
        )
        for t in tickets
    ]


@app.get("/health", response_model=HealthResponse)
async def health_check():
    """
    Health check endpoint for load balancers and monitoring.

    Returns 200 when healthy, 503 when degraded.
    """
    checks = {"api": "healthy"}

    # Check optional services
    try:
        import redis
        r = redis.Redis.from_url(os.environ.get("REDIS_URL", "redis://localhost:6379"), socket_timeout=1)
        r.ping()
        checks["redis"] = "healthy"
    except Exception:
        checks["redis"] = "unavailable"

    overall = "healthy" if all(v == "healthy" for v in checks.values()) else "degraded"

    return HealthResponse(
        status=overall,
        version="1.0.0",
        uptime_seconds=round(time.time() - app_start_time, 1),
        checks=checks,
    )


@app.get("/metrics", response_model=MetricsResponse)
async def get_metrics():
    """
    Basic performance metrics.

    In production, use Prometheus + Grafana for proper metrics.
    """
    total = metrics_store["total"]
    processed = metrics_store["processed"]
    avg_ms = (
        metrics_store["total_processing_ms"] / processed
        if processed > 0
        else 0.0
    )
    escalation_rate = (
        metrics_store["escalations"] / processed
        if processed > 0
        else 0.0
    )

    return MetricsResponse(
        total_tickets=total,
        processed_tickets=processed,
        pending_tickets=total - processed,
        avg_processing_time_ms=round(avg_ms, 1),
        escalation_rate=round(escalation_rate, 3),
    )


