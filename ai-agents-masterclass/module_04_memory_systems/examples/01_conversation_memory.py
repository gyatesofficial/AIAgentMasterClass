def demo_window_memory():
    """Show the sliding window in action."""
    print("\n" + "=" * 60)
    print("  Window Memory Demo (max_messages=6)")
    print("=" * 60)

    memory = WindowConversationMemory(
        system_prompt="You are a support agent.",
        max_messages=6,  # Small for demo
    )

    # Simulate a conversation with 8 turns
    for i in range(1, 9):
        memory.add_user_message(f"User message #{i}")
        memory.add_assistant_message(f"Agent response #{i}")
        print(f"  After turn {i}: {memory.summary()}")

    print(f"\n  Messages in context window:")
    for msg in memory.get_messages():
        role = msg["role"]
        content = msg["content"][:40]
        print(f"    [{role}]: {content}")

    print(f"\n  Note: Messages 1-4 were dropped (window overflow)")
    print(f"  System prompt is separate and always included")


def demo_summarizing_memory():
    """Show summarization kicking in."""
    print("\n" + "=" * 60)
    print("  Summarizing Memory Demo")
    print("=" * 60)

    memory = SummarizingConversationMemory(
        system_prompt="You are a support agent.",
        max_messages=10,
        summarize_after=6,  # Summarize after 6 messages
    )

    conversation = [
        ("I can't log in", "I'll help! What error do you see?"),
        ("It says invalid password", "Let's reset it. What's your email?"),
        ("alice@example.com", "Sent a reset link to alice@example.com"),
        ("Got it, but new password also fails", "Hmm, try incognito mode"),
        ("Works in incognito! What does that mean?", "Browser extension conflict. Disable them."),
        ("That fixed it! Thanks", "Great! Anything else?"),
        ("Actually I have a billing question", "Of course, what's your question?"),
        ("Was I charged twice in January?", "Let me check your billing history..."),
    ]

    for i, (user_msg, agent_msg) in enumerate(conversation, 1):
        memory.add_user_message(user_msg)
        memory.add_assistant_message(agent_msg)
        print(f"  Turn {i}: {memory.summary_stats()}")

    print(f"\n  Summary created: {memory._summary}")
    print(f"\n  Messages now in context ({len(memory._history)} recent):")
    for msg in memory._history:
        print(f"    [{msg.role}]: {msg.content[:50]}")


def demo_comparison():
    """Compare token counts between strategies."""
    print("\n" + "=" * 60)
    print("  Strategy Comparison: Token Efficiency")
    print("=" * 60)

    messages = [
        "Hello, I need help with my account",
        "Of course! What seems to be the issue?",
        "I can't log in after changing my password",
        "Let me help you reset it. What's your email?",
        "alice@example.com",
        "I've sent a reset link. Did you receive it?",
        "Yes! But now I have a different question",
        "Sure, what would you like to know?",
        "Why was I charged twice in December?",
        "That sounds like a duplicate charge. Let me investigate.",
    ]

    system = "You are a customer support agent. Be helpful and professional."

    window = WindowConversationMemory(system, max_messages=6)
    summarizing = SummarizingConversationMemory(system, max_messages=8, summarize_after=6)

    for i, msg in enumerate(messages):
        if i % 2 == 0:
            window.add_user_message(msg)
            summarizing.add_user_message(msg)
        else:
            window.add_assistant_message(msg)
            summarizing.add_assistant_message(msg)

    window_total = sum(len(m["content"]) for m in window.get_messages())
    summ_total = sum(len(m["content"]) for m in summarizing.get_messages())

    print(f"\n  After {len(messages)//2} turns:")
    print(f"\n  Window Memory:")
    print(f"    Messages sent to LLM: {len(window.get_messages())}")
    print(f"    Approx chars in context: {window_total:,}")
    print(f"    History preserved: Last {window.current_length} messages")

    print(f"\n  Summarizing Memory:")
    print(f"    Messages sent to LLM: {len(summarizing.get_messages())}")
    print(f"    Approx chars in context: {summ_total:,}")
    print(f"    Summaries created: {summarizing.summaries_created}")


if __name__ == "__main__":
    demo_window_memory()
    demo_summarizing_memory()
    demo_comparison()
